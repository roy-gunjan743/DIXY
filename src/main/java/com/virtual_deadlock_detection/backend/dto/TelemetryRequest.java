package com.virtual_deadlock_detection.backend.dto;

import com.virtual_deadlock_detection.backend.enums.ThreadState;
import lombok.Getter;
import lombok.Setter;

import java.time.LocalDateTime;

@Getter
@Setter
public class TelemetryRequest {

    /**
     * Application that generated this telemetry.
     *
     * Example:
     * deadlock-lab
     */
    private String appName;

    /**
     * Target JVM instance.
     *
     * Example:
     * pid-30260
     */
    private String instanceId;

    /**
     * JVMTI/JFR event type.
     *
     * Examples:
     * THREAD_START
     * THREAD_END
     * THREAD_BLOCKED
     * LOCK_OWNED
     * LOCK_RELEASE
     * THREAD_PARKED
     * LOCK_ACQUIRE
     * PINNING
     */
    private String eventType;

    private Long threadId;

    private String threadName;

    private ThreadState state;

    private String carrierThread;

    /**
     * Owner of the monitor when the event contains ownership information.
     */
    private Long ownerThreadId;

    private String ownerThreadName;

    /**
     * Native monitor identifier.
     */
    private String lockId;

    private String lockType;

    /**
     * Timestamp generated by the target JVM.
     */
    private LocalDateTime timestamp;
}
