package com.virtual_deadlock_detection.LockDetectionAgent.jfr;

import com.virtual_deadlock_detection.LockDetectionAgent.collector.EventCollector;
import jdk.jfr.consumer.RecordingStream;

import java.util.Objects;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.TimeUnit;

public class JfrRecorder {

    /**
     * Maximum time allowed for the JFR RecordingStream to become ready.
     *
     * This is only a startup guard. It does not affect normal event
     * collection or runtime detection behavior.
     */
    private static final long STARTUP_TIMEOUT_SECONDS = 10;

    /**
     * Used to identify the internal readiness-probe thread.
     *
     * JfrEventListener already ignores threads containing
     * "jfr event stream", so this probe will not become a DIXY
     * application event.
     */
    private static final String READINESS_THREAD_NAME =
            "jfr event stream readiness probe";

    private volatile RecordingStream recordingStream;

    public void start(EventCollector collector) {

        Objects.requireNonNull(collector, "collector");

        /*
         * Do not start a second RecordingStream if one is already active.
         *
         * This protects the recorder from accidental double-starts without
         * changing the normal lifecycle used by RecordingManager.
         */
        if (recordingStream != null) {
            throw new IllegalStateException(
                    "JFR RecordingStream is already running"
            );
        }

        RecordingStream stream = new RecordingStream();

        /*
         * startAsync() is asynchronous.
         *
         * The old implementation returned immediately after calling
         * startAsync(), which created this race:
         *
         *     startAsync()
         *          ↓
         *     start() returns
         *          ↓
         *     application creates virtual thread
         *          ↓
         *     virtual thread gets pinned
         *          ↓
         *     JFR consumer may not yet be ready
         *          ↓
         *     jdk.VirtualThreadPinned can be missed
         *
         * We therefore use an actual JFR ThreadStart event as a readiness
         * handshake.
         */
        CountDownLatch streamReady = new CountDownLatch(1);

        /*
         * Register the readiness handler BEFORE startAsync().
         *
         * This does not replace JfrEventListener's ThreadStart handler.
         * RecordingStream supports registering multiple handlers for the
         * same event.
         */
        stream.enable("jdk.ThreadStart");

        stream.onEvent("jdk.ThreadStart", event -> {
            streamReady.countDown();
        });

        /*
         * Register the normal DIXY event listeners exactly as before.
         *
         * This preserves all existing event types:
         *
         * - ThreadStart
         * - ThreadEnd
         * - JavaMonitorEnter
         * - JavaMonitorWait
         * - ThreadPark
         * - VirtualThreadPinned
         */
        JfrEventListener listener = new JfrEventListener(collector);
        listener.registerEvents(stream);

        /*
         * Publish the stream reference before starting it so stop() can
         * safely close it even if startup is interrupted.
         */
        recordingStream = stream;

        try {

            /*
             * IMPORTANT:
             *
             * startAsync() returns before the RecordingStream consumer
             * necessarily starts processing events.
             */
            stream.startAsync();

            /*
             * Generate a harmless ThreadStart event after startAsync().
             *
             * Once this event reaches our readiness handler, the JFR
             * consumer is definitely processing events.
             *
             * The thread name contains "jfr event stream", which is already
             * excluded by JfrEventListener.isIgnoredThread(...).
             */
            Thread readinessProbe = Thread.ofPlatform()
                    .name(READINESS_THREAD_NAME)
                    .start(() -> {
                        // Intentionally empty.
                        //
                        // The ThreadStart event generated by this thread
                        // is the readiness signal.
                    });

            /*
             * Wait until the JFR consumer has actually delivered the
             * ThreadStart event.
             */
            boolean ready = streamReady.await(
                    STARTUP_TIMEOUT_SECONDS,
                    TimeUnit.SECONDS
            );

            /*
             * The probe has no useful work after generating its ThreadStart
             * event, but wait briefly so it cannot outlive the recorder
             * startup path unnecessarily.
             */
            readinessProbe.join(1000);

            if (!ready) {

                /*
                 * JFR failed to become ready.
                 *
                 * Do not allow the application to continue as though event
                 * collection were active.
                 */
                stream.close();
                recordingStream = null;

                throw new IllegalStateException(
                        "JFR RecordingStream did not become ready within "
                                + STARTUP_TIMEOUT_SECONDS
                                + " seconds"
                );
            }

            System.out.println("JFR Recording Started.");

        } catch (InterruptedException e) {

            /*
             * Preserve the interruption status so callers/frameworks can
             * handle cancellation correctly.
             */
            Thread.currentThread().interrupt();

            stream.close();
            recordingStream = null;

            throw new IllegalStateException(
                    "Interrupted while waiting for JFR RecordingStream startup",
                    e
            );
        } catch (RuntimeException e) {

            /*
             * Make sure a partially-started JFR stream does not remain
             * active if startup fails for another reason.
             */
            stream.close();
            recordingStream = null;

            throw e;
        }
    }

    public void stop() {

        RecordingStream stream = recordingStream;

        if (stream != null) {

            /*
             * Clear the reference first so a concurrent lifecycle call
             * cannot accidentally reuse the closing stream.
             */
            recordingStream = null;

            stream.close();
        }
    }
}