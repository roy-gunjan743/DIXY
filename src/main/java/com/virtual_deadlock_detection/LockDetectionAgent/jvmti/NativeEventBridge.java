package com.virtual_deadlock_detection.LockDetectionAgent.jvmti;

import com.virtual_deadlock_detection.LockDetectionAgent.collector.EventCollector;
import com.virtual_deadlock_detection.LockDetectionAgent.dto.EventDTO;
import com.virtual_deadlock_detection.LockDetectionAgent.events.EventType;

import java.time.Instant;
import java.time.LocalDateTime;
import java.time.ZoneId;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;

public final class NativeEventBridge {

    /*
     * IMPORTANT:
     *
     * This must be the SAME EventCollector used by the main
     * VirtualDeadlockAgent.
     *
     * Do NOT create a new EventCollector here.
     */
    private static volatile EventCollector collector;

    /*
     * Recent events used by the DIXY CLI.
     */
    private static final int MAX_RECENT_EVENTS = 200;

    private static final List<EventDTO> recentEvents =
            Collections.synchronizedList(new ArrayList<>());

    private NativeEventBridge() {
        // Utility class.
    }

    /**
     * Connect the native JVMTI bridge to the shared EventCollector.
     */
    public static void setCollector(EventCollector eventCollector) {

        collector = eventCollector;

        System.out.println(
                "[JVMTI] NativeEventBridge connected to EventCollector"
        );
    }

    /**
     * Called by native JVMTI when a thread is waiting for a monitor
     * owned by another thread.
     *
     * Native signature:
     *
     * (JLjava/lang/String;JLjava/lang/String;JJ)V
     *
     * long   waitingThreadId
     * String waitingThreadName
     * long   ownerThreadId
     * String ownerThreadName
     * long   lockAddress
     * long   timestampMillis
     */
    public static void publishLockOwned(
            long waitingThreadId,
            String waitingThreadName,
            long ownerThreadId,
            String ownerThreadName,
            long lockAddress,
            long timestampMillis) {

        /*
         * ------------------------------------------------------------
         * IMPORTANT:
         * Ignore contention generated by the VDD/JFR infrastructure
         * itself.
         *
         * Without this filter, the JFR Event Stream thread can create
         * monitor events which enter this method again, producing a
         * feedback loop:
         *
         * JVMTI
         *   -> EventCollector
         *   -> JFR
         *   -> JFR Event Stream
         *   -> JVMTI
         *   -> ...
         *
         * Your previous run showed exactly this with:
         *
         * "JFR Event Stream 1"
         *
         * repeatedly contending with "main", eventually producing
         * StackOverflowError.
         * ------------------------------------------------------------
         */
        if (isInternalAgentThread(waitingThreadName)
                || isInternalAgentThread(ownerThreadName)) {

            return;
        }

        try {

            EventDTO dto = new EventDTO();

            dto.setEventType(EventType.LOCK_OWNED);

            dto.setThreadId(waitingThreadId);
            dto.setThreadName(waitingThreadName);

            dto.setOwnerThreadId(ownerThreadId);
            dto.setOwnerThreadName(ownerThreadName);

            dto.setLockAddress(lockAddress);

            dto.setTimestamp(
                    toLocalDateTime(timestampMillis)
            );

            /*
             * Keep a local bounded history for the CLI.
             */
            addRecentEvent(dto);

            /*
             * Use the shared EventCollector.
             */
            EventCollector currentCollector = collector;

            if (currentCollector == null) {

                System.err.println(
                        "[JVMTI] EventCollector is not initialized. "
                                + "Dropping LOCK_OWNED event."
                );

                return;
            }

            currentCollector.collect(dto);

            /*
             * Debug output.
             */
            System.out.println("--------------------------------");
            System.out.println("JVMTI -> Java");
            System.out.println("Event Type     : LOCK_OWNED");
            System.out.println(
                    "Waiting Thread : "
                            + waitingThreadName
                            + " ("
                            + waitingThreadId
                            + ")"
            );
            System.out.println(
                    "Owner Thread   : "
                            + ownerThreadName
                            + " ("
                            + ownerThreadId
                            + ")"
            );
            System.out.println(
                    "Lock Address   : "
                            + lockAddress
            );
            System.out.println("--------------------------------");

        } catch (Throwable t) {

            /*
             * Never allow an exception to escape through JNI/JVMTI.
             */
            System.err.println(
                    "[JVMTI] Exception in publishLockOwned: "
                            + t.getClass().getName()
                            + ": "
                            + t.getMessage()
            );

            t.printStackTrace(System.err);
        }
    }

    /**
     * Called by native JVMTI when a previously blocked thread
     * successfully acquires the monitor / wait edge is removed.
     *
     * Native signature:
     *
     * (JJJ)V
     *
     * long threadId
     * long lockAddress
     * long timestampMillis
     */
    public static void publishLockReleased(
            long threadId,
            long lockAddress,
            long timestampMillis) {

        try {

            EventDTO dto = new EventDTO();

            dto.setEventType(EventType.LOCK_RELEASE);

            dto.setThreadId(threadId);

            dto.setLockAddress(lockAddress);

            dto.setTimestamp(
                    toLocalDateTime(timestampMillis)
            );

            /*
             * Keep a local bounded history for the CLI.
             */
            addRecentEvent(dto);

            /*
             * Use the shared EventCollector.
             */
            EventCollector currentCollector = collector;

            if (currentCollector == null) {

                System.err.println(
                        "[JVMTI] EventCollector is not initialized. "
                                + "Dropping LOCK_RELEASE event."
                );

                return;
            }

            currentCollector.collect(dto);

            /*
             * Debug output.
             */
            System.out.println("--------------------------------");
            System.out.println("JVMTI -> Java");
            System.out.println("Event Type   : LOCK_RELEASE");
            System.out.println(
                    "Thread ID    : "
                            + threadId
            );
            System.out.println(
                    "Lock Address : "
                            + lockAddress
            );
            System.out.println("--------------------------------");

        } catch (Throwable t) {

            /*
             * Never allow an exception to escape through JNI/JVMTI.
             */
            System.err.println(
                    "[JVMTI] Exception in publishLockReleased: "
                            + t.getClass().getName()
                            + ": "
                            + t.getMessage()
            );

            t.printStackTrace(System.err);
        }
    }

    /**
     * Used by DIXY CLI commands.
     *
     * Returns a snapshot rather than the internal list.
     */
    public static List<EventDTO> getRecentEvents() {

        synchronized (recentEvents) {

            return new ArrayList<>(recentEvents);
        }
    }

    /**
     * Add an event to the bounded recent-event list.
     */
    private static void addRecentEvent(EventDTO dto) {

        synchronized (recentEvents) {

            recentEvents.add(dto);

            if (recentEvents.size() > MAX_RECENT_EVENTS) {

                recentEvents.remove(0);
            }
        }
    }

    /**
     * Converts the native millisecond timestamp into
     * the LocalDateTime expected by EventDTO.
     */
    private static LocalDateTime toLocalDateTime(
            long timestampMillis) {

        return LocalDateTime.ofInstant(
                Instant.ofEpochMilli(timestampMillis),
                ZoneId.systemDefault()
        );
    }

    /**
     * Identifies threads belonging to the VDD/JFR infrastructure.
     *
     * These threads must not be fed back into the same JVMTI
     * event-processing pipeline.
     */
    private static boolean isInternalAgentThread(
            String threadName) {

        if (threadName == null) {
            return false;
        }

        return threadName.startsWith("JFR Event Stream")
                || threadName.startsWith("JFR Periodic Tasks")
                || threadName.startsWith("JFR Recorder")
                || threadName.startsWith("HttpClient-")
                || threadName.startsWith("vld-thread-state-poller")
                || threadName.startsWith("VDD-")
                || threadName.startsWith("vdd-");
    }
}